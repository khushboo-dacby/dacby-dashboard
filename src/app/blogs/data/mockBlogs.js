const STORAGE_KEY = "dacby_mock_blogs_list";

export function getStoredBlogs() {
  if (typeof window === "undefined") {
    return INITIAL_BLOGS_DATA.blogs;
  }
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return INITIAL_BLOGS_DATA.blogs;
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_BLOGS_DATA.blogs;
  } catch (_) {
    return INITIAL_BLOGS_DATA.blogs;
  }
}

export function saveBlogLocally(newBlog) {
  if (typeof window === "undefined") return;
  try {
    const current = getStoredBlogs();
    const updated = [newBlog, ...current];
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
  } catch (_) {}
}

export function appendContentToBlog(blogId, newContentDocs) {
  if (typeof window === "undefined") return null;
  try {
    const current = getStoredBlogs();
    const docsToAdd = Array.isArray(newContentDocs) ? newContentDocs : [newContentDocs];
    const updated = current.map((blog) => {
      if (String(blog.id) === String(blogId)) {
        return {
          ...blog,
          content: [...(blog.content || []), ...docsToAdd]
        };
      }
      return blog;
    });
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated));
    return updated.find((b) => String(b.id) === String(blogId));
  } catch (_) {
    return null;
  }
}

export function formatBlogDate(createdAt) {
  if (!createdAt) return "Recent";
  const seconds = createdAt._seconds || createdAt.seconds;
  if (!seconds) return "Recent";
  const date = new Date(seconds * 1000);
  return date.toLocaleDateString("en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric"
  });
}

